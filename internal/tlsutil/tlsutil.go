// Package tlsutil builds TLS client configurations for connections from dcdash
// to backends (LDAP, Proxmox, Kea, ...): additional CAs, server name override
// and certificate pinning by fingerprint.
package tlsutil

import (
	"crypto/sha256"
	"crypto/subtle"
	"crypto/tls"
	"crypto/x509"
	"encoding/hex"
	"errors"
	"fmt"
	"os"

	"github.com/joernott/dcdash/internal/config"
)

// ClientConfig returns a TLS client configuration for serverName.
//
// Without a fingerprint the server certificate is verified against the system
// roots plus ca_file, including the host name. With a fingerprint only the
// SHA-256 fingerprint of the server's leaf certificate is compared, which pins
// exactly one certificate and is suitable for self-signed certificates (e.g.
// Samba's autogenerated certificate without subject alternative names).
func ClientConfig(c config.TLSClient, serverName string) (*tls.Config, error) {
	cfg := &tls.Config{MinVersion: tls.VersionTLS12, ServerName: serverName}
	if c.ServerName != "" {
		cfg.ServerName = c.ServerName
	}

	if c.CAFile != "" {
		pem, err := os.ReadFile(c.CAFile)
		if err != nil {
			return nil, fmt.Errorf("read ca_file: %w", err)
		}
		pool, err := x509.SystemCertPool()
		if err != nil {
			pool = x509.NewCertPool()
		}
		if !pool.AppendCertsFromPEM(pem) {
			return nil, fmt.Errorf("ca_file %s: no PEM certificates found", c.CAFile)
		}
		cfg.RootCAs = pool
	}

	if c.Fingerprint != "" {
		want, err := hex.DecodeString(c.NormalizedFingerprint())
		if err != nil || len(want) != sha256.Size {
			return nil, errors.New("fingerprint: must be a SHA-256 fingerprint")
		}
		// Chain and host name verification are replaced by the pin check below.
		// VerifyConnection (unlike VerifyPeerCertificate) also runs for resumed
		// sessions, so the pin cannot be bypassed by session resumption.
		cfg.InsecureSkipVerify = true // #nosec G402 -- verified by VerifyConnection (pinning)
		cfg.VerifyConnection = func(cs tls.ConnectionState) error {
			if len(cs.PeerCertificates) == 0 {
				return errors.New("server presented no certificate")
			}
			raw := cs.PeerCertificates[0].Raw
			got := sha256.Sum256(raw)
			if subtle.ConstantTimeCompare(got[:], want) != 1 {
				return fmt.Errorf("server certificate fingerprint %s does not match the pinned fingerprint", Fingerprint(raw))
			}
			return nil
		}
	}
	return cfg, nil
}

// Fingerprint returns the SHA-256 fingerprint of a DER certificate as
// colon-separated upper-case hex, as shown by `openssl x509 -fingerprint -sha256`.
func Fingerprint(der []byte) string {
	sum := sha256.Sum256(der)
	const hexDigits = "0123456789ABCDEF"
	out := make([]byte, 0, len(sum)*3-1)
	for i, b := range sum {
		if i > 0 {
			out = append(out, ':')
		}
		out = append(out, hexDigits[b>>4], hexDigits[b&0x0f])
	}
	return string(out)
}
